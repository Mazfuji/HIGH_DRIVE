def expand_5_to_7(rows: list[str]) -> list[str]:
    out = []
    column_map = (0, 1, 1, 2, 3, 3, 4)
    for row in rows:
        out.append("".join(row[src] for src in column_map))
    return out


def pixels_for(code: int) -> list[str]:
    if code == 127:
        return [
            "1111111",
            "1000001",
            "1011101",
            "1010101",
            "1011101",
            "1000001",
            "1111111",
        ]
    return expand_5_to_7(RAW_5X7[chr(code)])


def path_for(rows: list[str]) -> str:
    cmds = []
    for y, row in enumerate(rows):
        for x, bit in enumerate(row):
            if bit == "1":
                x0 = x * PX
                y0 = (ACTIVE - 1 - y) * PX
                cmds.append(f"M{x0},{y0}h{PX}v{PX}h-{PX}z")
    return "".join(cmds)


def symbol_for(code: int, rows: list[str]) -> str:
    rects = []
    for y, row in enumerate(rows):
        for x, bit in enumerate(row):
            if bit == "1":
                rects.append(f'      <rect x="{x}" y="{y}" width="1" height="1"/>')
    return "\n".join([f'    <symbol id="px-{code}" viewBox="0 0 8 8">', *rects, "    </symbol>"])


def unicode_attr(code: int) -> str:
    if code in {34, 38, 60, 62} or code < 32 or code == 127:
        return f"&#x{code:02X};"
    return html.escape(chr(code), quote=True)


def render() -> str:
    codes = list(range(32, 128))
    patterns = {code: pixels_for(code) for code in codes}
    glyphs = []
    symbols = []
    for code in codes:
        glyphs.append(
            f'      <glyph glyph-name="u{code:04X}" unicode="{unicode_attr(code)}" '
            f'horiz-adv-x="{CELL * PX}" d="{path_for(patterns[code])}"/>'
        )
        symbols.append(symbol_for(code, patterns[code]))

    scale = 5
    gap = 10
    label_h = 12
    cols = 16
    rows = 6
    grid_x = 24
    grid_y = 168
    tile = CELL * scale
    width = grid_x * 2 + cols * (tile + gap) - gap + 4
    height = grid_y + rows * (tile + label_h + gap) + 32

    preview = []
    for index, code in enumerate(codes):
        col = index % cols
        row = index // cols
        x = grid_x + col * (tile + gap)
        y = grid_y + row * (tile + label_h + gap)
        preview.extend(
            [
                f'    <rect x="{x - 2}" y="{y - 2}" width="{tile + 4}" height="{tile + 4}" fill="#111820" stroke="#263647"/>',
                f'    <use href="#px-{code}" x="{x}" y="{y}" width="{tile}" height="{tile}" fill="#ffffff" style="image-rendering:pixelated"/>',
                f'    <text x="{x + tile / 2}" y="{y + tile + 10}" text-anchor="middle" class="label">{code:03d}</text>',
            ]
        )

    sample = "ARCADE 8x8 FONT 0123456789"
    sample2 = "The quick brown fox jumps over lazy dogs."

    return "\n".join(
        [
            '<?xml version="1.0" encoding="UTF-8"?>',
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
            "  <title>Arcade 8x8 ASCII SVG bitmap font</title>",
            "  <desc>Self-contained SVG font covering ASCII 32 through 127. Glyphs advance on an 8x8 grid and draw inside a 7x7 pixel matrix.</desc>",
            "  <defs>",
            '    <font id="Arcade8x8ASCII" horiz-adv-x="800">',
            '      <font-face font-family="Arcade8x8ASCII" units-per-em="800" ascent="700" descent="100"/>',
            '      <missing-glyph horiz-adv-x="800" d="M0,0h700v700h-700zM100,100h500v500h-500z"/>',
            *glyphs,
            "    </font>",
            *symbols,
            "  </defs>",
            "  <style>",
            "    .bg { fill: #080c10; }",
            "    .title { fill: #ffffff; font: 700 22px system-ui, sans-serif; letter-spacing: 0; }",
            "    .meta { fill: #91a4b7; font: 12px system-ui, sans-serif; letter-spacing: 0; }",
            "    .sample { fill: #ffffff; font-family: Arcade8x8ASCII, monospace; font-size: 32px; }",
            "    .sample2 { fill: #ffffff; font-family: Arcade8x8ASCII, monospace; font-size: 24px; }",
            "    .label { fill: #91a4b7; font: 8px ui-monospace, SFMono-Regular, Menlo, monospace; letter-spacing: 0; }",
            "  </style>",
            '  <rect class="bg" width="100%" height="100%"/>',
            '  <text x="24" y="38" class="title">Arcade 8x8 ASCII SVG Font</text>',
            '  <text x="24" y="60" class="meta">ASCII 32-127, 8px advance, visible strokes constrained to a 7x7 pixel matrix.</text>',
            f'  <text x="24" y="104" class="sample">{html.escape(sample)}</text>',
            f'  <text x="24" y="138" class="sample2">{html.escape(sample2)}</text>',
            "  <g>",
            *preview,
            "  </g>",
            "</svg>",
            "",
        ]
    )


def main() -> None:
    SVG_PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {SVG_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
